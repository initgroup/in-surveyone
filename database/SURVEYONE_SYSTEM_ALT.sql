USING (
    SELECT 'ko' AS "LANG_CODE", 'Korean' AS "LANG_NAME", '한국어' AS "NATIVE_NAME", 10 AS "SORT_ORDER" FROM DUAL
    UNION ALL
    SELECT 'en', 'English', 'English', 20 FROM DUAL
    UNION ALL
