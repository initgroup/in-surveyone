/*
 * IN-SURVEYONE Oracle incremental schema script
 *
 * - Never drops, truncates, or recreates an existing table.
 * - Re-running the script skips objects and columns that already exist.
 * - New columns are appended to SURVEYONE_SYSTEM_DDL.sql in the same order.
 */
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK

SET SERVEROUTPUT ON

/*
 * 2026-08-11 object-prefix migration.
 * Legacy SVY$_TB_* tables are renamed in place, so their rows and grants stay intact.
 * If both legacy and target tables exist, the script stops instead of guessing or
 * overwriting data. Constraints and indexes are renamed after their owning tables.
 */
DECLARE
    V_NEW_NAME VARCHAR2(30 BYTE);
    V_COUNT NUMBER;
BEGIN
    FOR R IN (
        SELECT TABLE_NAME
          FROM USER_TABLES
         WHERE SUBSTR(TABLE_NAME, 1, 8) = 'SVY$_TB_'
         ORDER BY TABLE_NAME
    ) LOOP
        V_NEW_NAME := 'INIT$SVY_' || SUBSTR(R.TABLE_NAME, 6);
        SELECT COUNT(*)
          INTO V_COUNT
          FROM USER_TABLES
         WHERE TABLE_NAME = V_NEW_NAME;

        IF V_COUNT > 0 THEN
            RAISE_APPLICATION_ERROR(
                -20010
              , 'Both legacy and target tables exist: ' || R.TABLE_NAME || ', ' || V_NEW_NAME
            );
        END IF;

        EXECUTE IMMEDIATE 'ALTER TABLE "' || R.TABLE_NAME || '" RENAME TO "' || V_NEW_NAME || '"';
        DBMS_OUTPUT.PUT_LINE('[MIGRATE] TABLE ' || R.TABLE_NAME || ' -> ' || V_NEW_NAME);
    END LOOP;

    FOR R IN (
        SELECT C.TABLE_NAME, C.CONSTRAINT_NAME
          FROM USER_CONSTRAINTS C
         WHERE SUBSTR(C.TABLE_NAME, 1, 9) = 'INIT$SVY_'
           AND SUBSTR(C.CONSTRAINT_NAME, 1, 5) = 'SVY$_'
         ORDER BY C.TABLE_NAME, C.CONSTRAINT_NAME
    ) LOOP
        V_NEW_NAME := 'INIT$SVY_' || SUBSTR(R.CONSTRAINT_NAME, 6);
        SELECT COUNT(*)
          INTO V_COUNT
          FROM USER_CONSTRAINTS
         WHERE CONSTRAINT_NAME = V_NEW_NAME;

        IF V_COUNT > 0 THEN
            RAISE_APPLICATION_ERROR(
                -20011
              , 'Constraint target already exists: ' || V_NEW_NAME
            );
        END IF;

        EXECUTE IMMEDIATE
            'ALTER TABLE "' || R.TABLE_NAME || '" RENAME CONSTRAINT "'
         || R.CONSTRAINT_NAME || '" TO "' || V_NEW_NAME || '"';
        DBMS_OUTPUT.PUT_LINE('[MIGRATE] CONSTRAINT ' || R.CONSTRAINT_NAME || ' -> ' || V_NEW_NAME);
    END LOOP;

    FOR R IN (
        SELECT I.INDEX_NAME
          FROM USER_INDEXES I
         WHERE SUBSTR(I.TABLE_NAME, 1, 9) = 'INIT$SVY_'
           AND SUBSTR(I.INDEX_NAME, 1, 5) = 'SVY$_'
         ORDER BY I.INDEX_NAME
    ) LOOP
        V_NEW_NAME := 'INIT$SVY_' || SUBSTR(R.INDEX_NAME, 6);
        SELECT COUNT(*)
          INTO V_COUNT
          FROM USER_INDEXES
         WHERE INDEX_NAME = V_NEW_NAME;

        IF V_COUNT > 0 THEN
            RAISE_APPLICATION_ERROR(
                -20012
              , 'Index target already exists: ' || V_NEW_NAME
            );
        END IF;

        EXECUTE IMMEDIATE 'ALTER INDEX "' || R.INDEX_NAME || '" RENAME TO "' || V_NEW_NAME || '"';
        DBMS_OUTPUT.PUT_LINE('[MIGRATE] INDEX ' || R.INDEX_NAME || ' -> ' || V_NEW_NAME);
    END LOOP;
END;
/

DECLARE
    FUNCTION OBJECT_EXISTS(
        P_OBJECT_NAME IN VARCHAR2
      , P_OBJECT_TYPE IN VARCHAR2
    ) RETURN BOOLEAN IS
        V_COUNT NUMBER;
    BEGIN
        SELECT COUNT(*)
          INTO V_COUNT
          FROM USER_OBJECTS
         WHERE OBJECT_NAME = UPPER(P_OBJECT_NAME)
           AND OBJECT_TYPE = UPPER(P_OBJECT_TYPE);
        RETURN V_COUNT > 0;
    END;

    FUNCTION COLUMN_EXISTS(
        P_TABLE_NAME IN VARCHAR2
      , P_COLUMN_NAME IN VARCHAR2
    ) RETURN BOOLEAN IS
        V_COUNT NUMBER;
    BEGIN
        SELECT COUNT(*)
          INTO V_COUNT
          FROM USER_TAB_COLUMNS
         WHERE TABLE_NAME = UPPER(P_TABLE_NAME)
           AND COLUMN_NAME = UPPER(P_COLUMN_NAME);
        RETURN V_COUNT > 0;
    END;

    FUNCTION CONSTRAINT_EXISTS(
        P_CONSTRAINT_NAME IN VARCHAR2
    ) RETURN BOOLEAN IS
        V_COUNT NUMBER;
    BEGIN
        SELECT COUNT(*)
          INTO V_COUNT
          FROM USER_CONSTRAINTS
         WHERE CONSTRAINT_NAME = UPPER(P_CONSTRAINT_NAME);
        RETURN V_COUNT > 0;
    END;

    FUNCTION COLUMN_IS_NULLABLE(
        P_TABLE_NAME IN VARCHAR2
      , P_COLUMN_NAME IN VARCHAR2
    ) RETURN BOOLEAN IS
        V_NULLABLE USER_TAB_COLUMNS.NULLABLE%TYPE;
    BEGIN
        SELECT NULLABLE
          INTO V_NULLABLE
          FROM USER_TAB_COLUMNS
         WHERE TABLE_NAME = UPPER(P_TABLE_NAME)
           AND COLUMN_NAME = UPPER(P_COLUMN_NAME);
        RETURN V_NULLABLE = 'Y';
    END;

    PROCEDURE RUN_DDL(P_DDL IN CLOB, P_LABEL IN VARCHAR2) IS
    BEGIN
        EXECUTE IMMEDIATE P_DDL;
        DBMS_OUTPUT.PUT_LINE('[OK] ' || P_LABEL);
    EXCEPTION
        WHEN OTHERS THEN
            DBMS_OUTPUT.PUT_LINE('[ERROR] ' || P_LABEL || ' - ' || SQLERRM);
            RAISE;
    END;

    PROCEDURE CREATE_TABLE_IF_MISSING(P_TABLE_NAME IN VARCHAR2, P_DDL IN CLOB) IS
    BEGIN
        IF OBJECT_EXISTS(P_TABLE_NAME, 'TABLE') THEN
            DBMS_OUTPUT.PUT_LINE('[SKIP] TABLE ' || P_TABLE_NAME || ' already exists');
        ELSE
            RUN_DDL(P_DDL, 'CREATE TABLE ' || P_TABLE_NAME);
        END IF;
    END;

    PROCEDURE ADD_COLUMN_IF_MISSING(
        P_TABLE_NAME IN VARCHAR2
      , P_COLUMN_NAME IN VARCHAR2
      , P_COLUMN_DEFINITION IN VARCHAR2
    ) IS
    BEGIN
        IF COLUMN_EXISTS(P_TABLE_NAME, P_COLUMN_NAME) THEN
            DBMS_OUTPUT.PUT_LINE('[SKIP] COLUMN ' || P_TABLE_NAME || '.' || P_COLUMN_NAME || ' already exists');
        ELSE
            RUN_DDL(
                'ALTER TABLE "' || UPPER(P_TABLE_NAME) || '" ADD ('
             || '"' || UPPER(P_COLUMN_NAME) || '" ' || P_COLUMN_DEFINITION || ')'
              , 'ADD COLUMN ' || P_TABLE_NAME || '.' || P_COLUMN_NAME
            );
        END IF;
    END;

    PROCEDURE WIDEN_VARCHAR2_IF_NEEDED(
        P_TABLE_NAME IN VARCHAR2
      , P_COLUMN_NAME IN VARCHAR2
      , P_MIN_BYTES IN PLS_INTEGER
    ) IS
        V_DATA_TYPE USER_TAB_COLUMNS.DATA_TYPE%TYPE;
        V_DATA_LENGTH USER_TAB_COLUMNS.DATA_LENGTH%TYPE;
    BEGIN
        SELECT DATA_TYPE, DATA_LENGTH
          INTO V_DATA_TYPE, V_DATA_LENGTH
          FROM USER_TAB_COLUMNS
         WHERE TABLE_NAME = UPPER(P_TABLE_NAME)
           AND COLUMN_NAME = UPPER(P_COLUMN_NAME);

        IF V_DATA_TYPE <> 'VARCHAR2' THEN
            RAISE_APPLICATION_ERROR(
                -20013
              , P_TABLE_NAME || '.' || P_COLUMN_NAME || ' must be VARCHAR2 before widening'
            );
        ELSIF V_DATA_LENGTH < P_MIN_BYTES THEN
            RUN_DDL(
                'ALTER TABLE "' || UPPER(P_TABLE_NAME) || '" MODIFY ('
             || '"' || UPPER(P_COLUMN_NAME) || '" VARCHAR2('
             || TO_CHAR(P_MIN_BYTES) || ' BYTE))'
              , 'WIDEN COLUMN ' || P_TABLE_NAME || '.' || P_COLUMN_NAME
            );
        ELSE
            DBMS_OUTPUT.PUT_LINE(
                '[SKIP] COLUMN ' || P_TABLE_NAME || '.' || P_COLUMN_NAME
             || ' already has at least ' || TO_CHAR(P_MIN_BYTES) || ' bytes'
            );
        END IF;
    END;

    PROCEDURE CREATE_INDEX_IF_MISSING(P_INDEX_NAME IN VARCHAR2, P_DDL IN CLOB) IS
    BEGIN
        IF OBJECT_EXISTS(P_INDEX_NAME, 'INDEX') THEN
            DBMS_OUTPUT.PUT_LINE('[SKIP] INDEX ' || P_INDEX_NAME || ' already exists');
        ELSE
            RUN_DDL(P_DDL, 'CREATE INDEX ' || P_INDEX_NAME);
        END IF;
    END;

    PROCEDURE ADD_CONSTRAINT_IF_MISSING(
        P_TABLE_NAME IN VARCHAR2
      , P_CONSTRAINT_NAME IN VARCHAR2
      , P_DEFINITION IN CLOB
    ) IS
    BEGIN
        IF CONSTRAINT_EXISTS(P_CONSTRAINT_NAME) THEN
            DBMS_OUTPUT.PUT_LINE('[SKIP] CONSTRAINT ' || P_CONSTRAINT_NAME || ' already exists');
        ELSE
            RUN_DDL(
                'ALTER TABLE "' || UPPER(P_TABLE_NAME) || '" ADD CONSTRAINT "'
             || UPPER(P_CONSTRAINT_NAME) || '" ' || P_DEFINITION
              , 'ADD CONSTRAINT ' || P_CONSTRAINT_NAME
            );
        END IF;
    END;
