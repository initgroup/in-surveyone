CREATE OR REPLACE FUNCTION "INIT$SVY_FN_GUEST_CAN" (
    P_TENANT_ID IN VARCHAR2
  , P_USER_ID IN VARCHAR2
  , P_CAPABILITY_CODE IN VARCHAR2
) RETURN CHAR AUTHID DEFINER IS
    V_GUEST_MODE "INIT$SVY_TB_USER"."GUEST_MODE_CODE"%TYPE;
    V_USER_USE "INIT$SVY_TB_USER"."USE_YN"%TYPE;
    V_TENANT_STATUS "INIT$SVY_TB_TENANT"."STATUS_CODE"%TYPE;
    V_TENANT_EXPIRES "INIT$SVY_TB_TENANT"."EXPIRES_AT"%TYPE;
    V_ALLOWED CHAR(1 BYTE);
BEGIN
    SELECT U."GUEST_MODE_CODE", U."USE_YN", T."STATUS_CODE", T."EXPIRES_AT"
      INTO V_GUEST_MODE, V_USER_USE, V_TENANT_STATUS, V_TENANT_EXPIRES
      FROM "INIT$SVY_TB_USER" U
      JOIN "INIT$SVY_TB_TENANT" T
        ON T."TENANT_ID" = U."TENANT_ID"
     WHERE U."TENANT_ID" = P_TENANT_ID
       AND U."USER_ID" = P_USER_ID;

    IF V_USER_USE <> 'Y'
       OR V_TENANT_STATUS <> 'ACTIVE'
       OR (V_TENANT_EXPIRES IS NOT NULL AND V_TENANT_EXPIRES <= SYSTIMESTAMP) THEN
        RETURN 'N';
    END IF;

    IF V_GUEST_MODE = 'NONE' THEN
        RETURN 'Y';
    END IF;

    SELECT NVL(MAX(C."ALLOWED_YN"), 'N')
      INTO V_ALLOWED
      FROM "INIT$SVY_TB_GUEST_CAP" C
     WHERE C."TENANT_ID" = P_TENANT_ID
       AND C."USER_ID" = P_USER_ID
       AND C."CAPABILITY_CODE" = UPPER(TRIM(P_CAPABILITY_CODE))
       AND (C."EXPIRES_AT" IS NULL OR C."EXPIRES_AT" > SYSTIMESTAMP);

    RETURN V_ALLOWED;
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RETURN 'N';
END;
