CREATE OR REPLACE FUNCTION "INIT$SVY_FN_I18N_TEXT" (
    P_TENANT_ID IN VARCHAR2
  , P_SURVEY_ID IN VARCHAR2
  , P_VERSION_NO IN NUMBER
  , P_LANG_CODE IN VARCHAR2
  , P_RESOURCE_TYPE_CODE IN VARCHAR2
  , P_RESOURCE_ID IN VARCHAR2
  , P_FIELD_CODE IN VARCHAR2
  , P_FALLBACK_TEXT IN CLOB DEFAULT NULL
) RETURN CLOB AUTHID DEFINER IS
    V_TEXT CLOB;
BEGIN
    BEGIN
        SELECT I."TEXT_VALUE"
          INTO V_TEXT
          FROM "INIT$SVY_TB_SURVEY_I18N" I
         WHERE I."TENANT_ID" = P_TENANT_ID
           AND I."SURVEY_ID" = P_SURVEY_ID
           AND I."VERSION_NO" = NVL(P_VERSION_NO, 0)
           AND LOWER(I."LANG_CODE") = LOWER(REPLACE(TRIM(P_LANG_CODE), '_', '-'))
           AND I."RESOURCE_TYPE_CODE" = UPPER(TRIM(P_RESOURCE_TYPE_CODE))
           AND I."RESOURCE_ID" = P_RESOURCE_ID
           AND I."FIELD_CODE" = UPPER(TRIM(P_FIELD_CODE));
        RETURN V_TEXT;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            NULL;
    END;

    BEGIN
        IF NVL(P_VERSION_NO, 0) > 0 THEN
            /* Published fallback comes from the immutable version snapshot. */
            SELECT I."TEXT_VALUE"
              INTO V_TEXT
              FROM "INIT$SVY_TB_SURVEY_VERSION" V
              JOIN "INIT$SVY_TB_SURVEY_I18N" I
                ON I."TENANT_ID" = V."TENANT_ID"
               AND I."SURVEY_ID" = V."SURVEY_ID"
               AND I."VERSION_NO" = V."VERSION_NO"
             WHERE V."TENANT_ID" = P_TENANT_ID
               AND V."SURVEY_ID" = P_SURVEY_ID
               AND V."VERSION_NO" = P_VERSION_NO
               AND LOWER(I."LANG_CODE") = LOWER(
                    COALESCE(
                        JSON_VALUE(
                            V."SNAPSHOT_JSON"
                          , '$.languages.defaultLocale'
                            RETURNING VARCHAR2(20) NULL ON ERROR
                        )
                      , JSON_VALUE(
                            V."SNAPSHOT_JSON"
                          , '$.defaultLocale'
                            RETURNING VARCHAR2(20) NULL ON ERROR
                        )
                    )
               )
               AND I."RESOURCE_TYPE_CODE" = UPPER(TRIM(P_RESOURCE_TYPE_CODE))
               AND I."RESOURCE_ID" = P_RESOURCE_ID
               AND I."FIELD_CODE" = UPPER(TRIM(P_FIELD_CODE))
               AND ROWNUM = 1;
        ELSE
            /* Draft fallback follows the current editable language settings. */
            SELECT I."TEXT_VALUE"
              INTO V_TEXT
              FROM "INIT$SVY_TB_SURVEY_LANG" L
              JOIN "INIT$SVY_TB_SURVEY_I18N" I
                ON I."TENANT_ID" = L."TENANT_ID"
               AND I."SURVEY_ID" = L."SURVEY_ID"
               AND I."LANG_CODE" = L."LANG_CODE"
             WHERE L."TENANT_ID" = P_TENANT_ID
               AND L."SURVEY_ID" = P_SURVEY_ID
               AND L."DEFAULT_YN" = 'Y'
               AND L."USE_YN" = 'Y'
               AND I."VERSION_NO" = 0
               AND I."RESOURCE_TYPE_CODE" = UPPER(TRIM(P_RESOURCE_TYPE_CODE))
               AND I."RESOURCE_ID" = P_RESOURCE_ID
               AND I."FIELD_CODE" = UPPER(TRIM(P_FIELD_CODE))
               AND ROWNUM = 1;
        END IF;
        RETURN V_TEXT;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RETURN P_FALLBACK_TEXT;
    END;
END;
