-- [RESPONSE_LIST_BY_OWNER]
SELECT R.RESPONSE_ID
     , R.SURVEY_ID
     , R.SURVEY_VERSION_NO
     , R.RESPONDENT_KEY_HASH
     , R.METADATA_JSON
     , R.SUBMITTED_AT
  FROM "INIT$SVY_TB_RESPONSE" R
  JOIN "INIT$SVY_TB_SURVEY" S
    ON S.TENANT_ID = R.TENANT_ID
   AND S.SURVEY_ID = R.SURVEY_ID
 WHERE R.SURVEY_ID = :surveyId
   AND R.TENANT_ID = :tenantId
   AND S.OWNER_USER_ID = :ownerUserId
 ORDER BY R.SUBMITTED_AT DESC
        , R.RESPONSE_ID DESC
 OFFSET :offset ROWS FETCH NEXT :limit ROWS ONLY
;

-- [RESPONSE_ANSWER_LIST_BY_OWNER]
WITH PAGE_RESPONSE AS (
    SELECT R.RESPONSE_ID
         , R.TENANT_ID
         , R.SUBMITTED_AT
      FROM "INIT$SVY_TB_RESPONSE" R
      JOIN "INIT$SVY_TB_SURVEY" S
        ON S.TENANT_ID = R.TENANT_ID
       AND S.SURVEY_ID = R.SURVEY_ID
     WHERE R.SURVEY_ID = :surveyId
       AND R.TENANT_ID = :tenantId
       AND S.OWNER_USER_ID = :ownerUserId
     ORDER BY R.SUBMITTED_AT DESC
            , R.RESPONSE_ID DESC
     OFFSET :offset ROWS FETCH NEXT :limit ROWS ONLY
)
SELECT A.RESPONSE_ID
     , A.TENANT_ID
     , A.QUESTION_ID
     , A.ANSWER_VALUE_JSON
  FROM "INIT$SVY_TB_RESPONSE_ANSWER" A
  JOIN PAGE_RESPONSE R
    ON R.TENANT_ID = A.TENANT_ID
   AND R.RESPONSE_ID = A.RESPONSE_ID
 WHERE R.TENANT_ID = :tenantId
   AND A.TENANT_ID = :tenantId
 ORDER BY R.SUBMITTED_AT DESC
        , R.RESPONSE_ID DESC
        , A.QUESTION_ID
;

-- [RESPONSE_REPORT_LIST]
SELECT R.RESPONSE_ID
     , R.SURVEY_VERSION_NO
     , R.SUBMITTED_AT
     , A.QUESTION_ID
     , A.ANSWER_VALUE_JSON
  FROM "INIT$SVY_TB_RESPONSE" R
  JOIN "INIT$SVY_TB_SURVEY" S
    ON S.TENANT_ID = R.TENANT_ID
   AND S.SURVEY_ID = R.SURVEY_ID
  LEFT JOIN "INIT$SVY_TB_RESPONSE_ANSWER" A
    ON A.TENANT_ID = R.TENANT_ID
   AND A.RESPONSE_ID = R.RESPONSE_ID
 WHERE R.SURVEY_ID = :surveyId
   AND R.TENANT_ID = :tenantId
   AND R.SURVEY_VERSION_NO = :surveyVersionNo
   AND S.OWNER_USER_ID = :ownerUserId
   AND (:cutoffExclusive IS NULL OR R.SUBMITTED_AT < :cutoffExclusive)
 ORDER BY R.SUBMITTED_AT
        , A.QUESTION_ID
;

