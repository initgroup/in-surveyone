       TEMPLATE_CODE, VERSION_NO, SNAPSHOT_JSON, CONTENT_HASH, PUBLISHED_AT
)
SELECT T.TEMPLATE_CODE
     , T.CURRENT_VERSION_NO
     , :snapshotJson
     , :contentHash
     , NVL(T.UPDATED_AT, T.CREATED_AT)
  FROM "INIT$SVY_TB_TEMPLATE" T
