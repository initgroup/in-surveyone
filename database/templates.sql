     , S.SURVEY_TITLE
     , S.DESCRIPTION
     , S.CATEGORY_CODE
     , S.DRAFT_JSON
     , S.CREATED_AT
     , S.UPDATED_AT
  FROM "INIT$SVY_TB_SURVEY" S
 WHERE S.TENANT_ID = :tenantId
   AND S.OWNER_USER_ID = :ownerUserId
   AND S.ADMIN_TEMPLATE_YN = 'Y'
   AND S.STATUS_CODE = 'DRAFT'
   AND NOT EXISTS (
          SELECT 1
            FROM "INIT$SVY_TB_TEMPLATE" T
           WHERE T.SOURCE_SURVEY_ID = S.SURVEY_ID
             AND T.STATUS_CODE <> 'DELETED'
       )
 ORDER BY S.UPDATED_AT DESC
;

