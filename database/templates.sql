-- [ADMIN_TEMPLATE_LIST]
SELECT T.TEMPLATE_CODE
     , T.TEMPLATE_TITLE
     , T.CATEGORY_CODE
     , T.DESCRIPTION
     , T.CONTENT_JSON
     , T.STATUS_CODE
     , T.CURRENT_VERSION_NO
     , T.REVISION_NO
     , T.SOURCE_SURVEY_ID
     , T.CREATED_AT
     , T.UPDATED_AT
     , (SELECT V.PUBLISHED_AT
          FROM "INIT$SVY_TB_TEMPLATE_VERSION" V
         WHERE V.TEMPLATE_CODE = T.TEMPLATE_CODE
           AND V.VERSION_NO = T.CURRENT_VERSION_NO) AS CURRENT_PUBLISHED_AT
     , (SELECT COUNT(*)
         FROM "INIT$SVY_TB_SURVEY" S
         WHERE S.TEMPLATE_CODE = T.TEMPLATE_CODE
           AND S.STATUS_CODE <> 'DELETED'
           AND S.ADMIN_TEMPLATE_YN = 'N') AS USE_COUNT
  FROM "INIT$SVY_TB_TEMPLATE" T
 WHERE T.STATUS_CODE <> 'DELETED'
 ORDER BY NVL(T.UPDATED_AT, T.CREATED_AT) DESC
        , T.TEMPLATE_CODE
;

