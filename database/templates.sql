-- [ADMIN_TEMPLATE_UPSERT]
MERGE INTO "INIT$SVY_TB_TEMPLATE" T
USING (SELECT :templateCode AS TEMPLATE_CODE FROM DUAL) S
   ON (T.TEMPLATE_CODE = S.TEMPLATE_CODE)
 WHEN MATCHED THEN UPDATE SET
      T.TEMPLATE_TITLE = :templateTitle
    , T.CATEGORY_CODE = :categoryCode
    , T.DESCRIPTION = :description
    , T.CONTENT_JSON = :contentJson
    , T.USE_YN = 'Y'
    , T.STATUS_CODE = 'ACTIVE'
    , T.CURRENT_VERSION_NO = :versionNo
    , T.REVISION_NO = T.REVISION_NO + 1
    , T.SOURCE_SURVEY_ID = :sourceSurveyId
    , T.UPDATED_BY = :actorUserId
    , T.UPDATED_AT = SYSTIMESTAMP
 WHEN NOT MATCHED THEN INSERT (
      TEMPLATE_CODE, TEMPLATE_TITLE, CATEGORY_CODE, DESCRIPTION, CONTENT_JSON,
      USE_YN, STATUS_CODE, CURRENT_VERSION_NO, REVISION_NO, SOURCE_SURVEY_ID,
      CREATED_BY, UPDATED_BY, CREATED_AT, UPDATED_AT
 ) VALUES (
      :templateCode, :templateTitle, :categoryCode, :description, :contentJson,
      'Y', 'ACTIVE', :versionNo, 1, :sourceSurveyId,
      :actorUserId, :actorUserId, SYSTIMESTAMP, SYSTIMESTAMP
 )
;

-- [ADMIN_TEMPLATE_PATCH]
UPDATE "INIT$SVY_TB_TEMPLATE"
   SET TEMPLATE_TITLE = COALESCE(:templateTitle, TEMPLATE_TITLE)
     , CATEGORY_CODE = COALESCE(:categoryCode, CATEGORY_CODE)
     , DESCRIPTION = CASE WHEN :descriptionSet = 'Y' THEN :description ELSE DESCRIPTION END
     , STATUS_CODE = COALESCE(:statusCode, STATUS_CODE)
     , USE_YN = CASE COALESCE(:statusCode, STATUS_CODE) WHEN 'ACTIVE' THEN 'Y' ELSE 'N' END
     , REVISION_NO = REVISION_NO + 1
     , UPDATED_BY = :actorUserId
     , UPDATED_AT = SYSTIMESTAMP
 WHERE TEMPLATE_CODE = :templateCode
;

-- [ADMIN_TEMPLATE_SOURCE_DELETE]
