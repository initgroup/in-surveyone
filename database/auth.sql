-- [ADMIN_MEMBER_COUNT]
SELECT COUNT(*) AS MEMBER_COUNT
  FROM "INIT$SVY_TB_USER" U
  JOIN "INIT$SVY_TB_TENANT" T ON T.TENANT_ID = U.TENANT_ID
 WHERE 1 = CASE
       WHEN :memberType = 'ALL' THEN 1
       WHEN :memberType = 'MEMBER' AND U.GUEST_YN = 'N' THEN 1
       WHEN :memberType = 'GUEST' AND U.GUEST_YN = 'Y' THEN 1
       ELSE 0
   END
   AND (
       :queryPattern IS NULL
       OR LOWER(U.LOGIN_ID) LIKE :queryPattern
       OR LOWER(U.USER_NAME) LIKE :queryPattern
       OR LOWER(NVL(U.EMAIL, '')) LIKE :queryPattern
       OR LOWER(T.TENANT_NAME) LIKE :queryPattern
   )
;

-- [ADMIN_MEMBER_PAGE]
SELECT U.USER_ID
     , U.TENANT_ID
     , U.LOGIN_ID
     , U.USER_NAME
     , U.EMAIL
     , U.ROLE_CODE
     , U.SYSTEM_ADMIN_YN
     , U.GUEST_YN
     , U.GUEST_MODE_CODE
     , U.USE_YN
     , U.WITHDRAWN_AT
     , U.CREATED_AT
     , T.TENANT_NAME
     , T.EXPIRES_AT AS TENANT_EXPIRES_AT
     , (SELECT MAX(S.CREATED_AT) FROM "INIT$SVY_TB_AUTH_SESSION" S WHERE S.USER_ID = U.USER_ID) AS LAST_LOGIN_AT
  FROM "INIT$SVY_TB_USER" U
  JOIN "INIT$SVY_TB_TENANT" T ON T.TENANT_ID = U.TENANT_ID
 WHERE 1 = CASE
       WHEN :memberType = 'ALL' THEN 1
       WHEN :memberType = 'MEMBER' AND U.GUEST_YN = 'N' THEN 1
       WHEN :memberType = 'GUEST' AND U.GUEST_YN = 'Y' THEN 1
       ELSE 0
   END
   AND (
       :queryPattern IS NULL
       OR LOWER(U.LOGIN_ID) LIKE :queryPattern
       OR LOWER(U.USER_NAME) LIKE :queryPattern
       OR LOWER(NVL(U.EMAIL, '')) LIKE :queryPattern
       OR LOWER(T.TENANT_NAME) LIKE :queryPattern
   )
 ORDER BY U.CREATED_AT DESC, U.USER_ID
 OFFSET :offsetRows ROWS FETCH NEXT :limitRows ROWS ONLY
;

