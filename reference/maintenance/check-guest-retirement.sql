-- Read-only DBA preflight. Run as a DBA, not as the application account.
-- Bind SVY_OWNER to the actual application object owner without printing it.
-- Both counts must be zero before physical guest-data retirement.
-- This script never changes objects, users, grants, constraints or data.
SELECT COUNT(*) AS EXTERNAL_REFERENCE_COUNT
  FROM DBA_CONSTRAINTS C
  JOIN DBA_CONSTRAINTS P
    ON C.R_OWNER = P.OWNER
   AND C.R_CONSTRAINT_NAME = P.CONSTRAINT_NAME
 WHERE C.CONSTRAINT_TYPE = 'R'
   AND P.OWNER = UPPER(:SVY_OWNER)
   AND SUBSTR(P.TABLE_NAME, 1, 9) = 'INIT$SVY_'
   AND C.OWNER <> P.OWNER;

SELECT COUNT(*) AS UNREVIEWED_CHILD_TABLE_COUNT
  FROM DBA_CONSTRAINTS C
  JOIN DBA_CONSTRAINTS P
    ON C.R_OWNER = P.OWNER
   AND C.R_CONSTRAINT_NAME = P.CONSTRAINT_NAME
 WHERE C.CONSTRAINT_TYPE = 'R'
   AND P.OWNER = UPPER(:SVY_OWNER)
   AND SUBSTR(P.TABLE_NAME, 1, 9) = 'INIT$SVY_'
   AND C.OWNER = P.OWNER
   AND C.TABLE_NAME NOT IN (
       'INIT$SVY_TB_AUDIT_LOG', 'INIT$SVY_TB_REPORT_RUN',
       'INIT$SVY_TB_REPORT_DEFINITION', 'INIT$SVY_TB_DELIVERY',
       'INIT$SVY_TB_DELIVERY_RECIPIENT', 'INIT$SVY_TB_DELIVERY_TARGET',
       'INIT$SVY_TB_DELIVERY_BATCH', 'INIT$SVY_TB_SURVEY_DEPLOYMENT',
       'INIT$SVY_TB_SURVEY_SKIN', 'INIT$SVY_TB_RESPONSE_ANSWER',
       'INIT$SVY_TB_RESPONSE', 'INIT$SVY_TB_SURVEY_I18N',
       'INIT$SVY_TB_SURVEY_LANG', 'INIT$SVY_TB_SURVEY_VERSION',
       'INIT$SVY_TB_SURVEY', 'INIT$SVY_TB_GUEST_CAP',
       'INIT$SVY_TB_AUTH_SESSION', 'INIT$SVY_TB_USER',
       'INIT$SVY_TB_TENANT', 'INIT$SVY_TB_TEMPLATE',
       'INIT$SVY_TB_TEMPLATE_VERSION'
   );
